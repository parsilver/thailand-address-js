// Generates src/generated/schema.ts from schema/schema.json, the dataset's
// JSON Schema for the pinned snapshot. Run `pnpm gen:types` after updating
// the schema; `--check` fails when the committed file is out of date (CI).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const schema = JSON.parse(readFileSync(join(root, 'schema/schema.json'), 'utf8'))
const out = join(root, 'src/generated/schema.ts')

// The schema has no root type, only $defs. Wrap the defs the package reads so
// each one is emitted as a named, exported type.
const wanted = [
  'province',
  'district',
  'subdistrict',
  'postal_code_link',
  'postal_codes_index_entry',
  'by_province_file',
  'provinces_file',
  'districts_file',
  'subdistricts_file',
  'postal_codes_index_file',
]
const wrapper = {
  $defs: schema.$defs,
  title: 'DatasetSchema',
  type: 'object',
  additionalProperties: false,
  properties: Object.fromEntries(wanted.map((k) => [k, { $ref: `#/$defs/${k}` }])),
}

const body = await compile(wrapper, 'DatasetSchema', {
  bannerComment: [
    '/* eslint-disable */',
    '// Generated by scripts/gen-types.mjs from schema/schema.json. Do not edit.',
    `// Schema: ${schema.$id ?? 'unknown'}`,
  ].join('\n'),
  additionalProperties: false,
  declareExternallyReferenced: true,
  unreachableDefinitions: false,
  format: true,
  style: { singleQuote: true, semi: false, printWidth: 100 },
})

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(out, 'utf8')
  } catch {
    // No committed file yet: it differs.
  }
  if (current !== body) {
    console.error('src/generated/schema.ts is out of date. Run `pnpm gen:types` and commit it.')
    process.exit(1)
  }
  console.log('generated types are up to date')
} else {
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, body)
  console.log(`wrote ${out}`)
}
